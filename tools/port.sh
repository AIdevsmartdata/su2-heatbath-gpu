#!/usr/bin/env bash
# port.sh — generates src/su2_cuda.cu (mechanical HIP -> CUDA port of src/su2_hip.cpp) and src/port.diff.
# The ONLY changes are: the runtime include, the prefix of the error message, the device-name line
# printed at start-up, and the "engine"/"backend" strings of manifest.json. Each substitution must
# apply exactly once, otherwise the script fails. Two comment lines are prepended.
# Usage: tools/port.sh            regenerate src/su2_cuda.cu and src/port.diff
#        tools/port.sh --check    regenerate in a temporary directory and compare (rc 1 on mismatch)
set -eu
cd "$(dirname "$0")/.."
SRC=src/su2_hip.cpp
MODE=${1:-write}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# fixed strings that must each occur exactly once in the HIP source
need() { n=$(grep -cF -- "$1" "$SRC" || true); [ "$n" = 1 ] || { echo "port.sh: expected exactly one occurrence of: $1 (found $n)" >&2; exit 2; }; }
need '#include <hip/hip_runtime.h>'
need 'ERREUR HIP %s:%d'
need 'fprintf(stderr, "# su2_hip : %d GPU, %s %s\n", ndev, pr.name, pr.gcnArchName);'
need '\"engine\":\"su2_hip\"'
need '\"backend\":\"HIP gfx1151 FP64\"'

{
  echo "// su2_cuda.cu — MECHANICAL PORT of su2_hip.cpp to CUDA, generated by tools/port.sh (do not edit)."
  echo "// Full diff: src/port.diff. Algorithm, RNG and output formats are unchanged."
  sed -e 's|#include <hip/hip_runtime.h>|#include "hip2cuda.h"|' \
      -e 's|ERREUR HIP %s:%d|ERREUR CUDA %s:%d|' \
      -e 's|fprintf(stderr, "# su2_hip : %d GPU, %s %s\\n", ndev, pr.name, pr.gcnArchName);|fprintf(stderr, "# su2_cuda : %d GPU, %s sm_%d%d\\n", ndev, pr.name, pr.major, pr.minor);|' \
      -e 's|\\"engine\\":\\"su2_hip\\"|\\"engine\\":\\"su2_cuda\\"|' \
      -e 's|\\"backend\\":\\"HIP gfx1151 FP64\\"|\\"backend\\":\\"CUDA sm_120 FP64 (portage de su2_hip)\\"|' \
      "$SRC"
} > "$TMP/su2_cuda.cu"
diff -u --label src/su2_hip.cpp --label src/su2_cuda.cu "$SRC" "$TMP/su2_cuda.cu" > "$TMP/port.diff" || true
# sanity: exactly 2 added header lines + 4 changed lines (engine and backend share one line)
nplus=$(grep -c '^+[^+]' "$TMP/port.diff" || true); nminus=$(grep -c '^-[^-]' "$TMP/port.diff" || true)
[ "$nplus" = 6 ] && [ "$nminus" = 4 ] || { echo "port.sh: unexpected diff size (+$nplus/-$nminus, expected +6/-4)" >&2; exit 3; }

if [ "$MODE" = "--check" ]; then
  rc=0
  cmp -s "$TMP/su2_cuda.cu" src/su2_cuda.cu || { echo "PORT CHECK FAIL: src/su2_cuda.cu differs from the generated port" >&2; rc=1; }
  cmp -s "$TMP/port.diff" src/port.diff || { echo "PORT CHECK FAIL: src/port.diff is stale" >&2; rc=1; }
  [ $rc = 0 ] && echo "PORT CHECK OK (src/su2_cuda.cu and src/port.diff match tools/port.sh output)"
  exit $rc
fi
cp "$TMP/su2_cuda.cu" src/su2_cuda.cu
cp "$TMP/port.diff" src/port.diff
echo "port.sh: wrote src/su2_cuda.cu and src/port.diff"
